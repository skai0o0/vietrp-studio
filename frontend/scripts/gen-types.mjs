/* global URL, console */
// Converts src/types/generated/schemas/*.json into .ts files next to them (one level up).
import { readdir, readFile, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = fileURLToPath(new URL("../src/types/generated/", import.meta.url));
const schemaDir = join(root, "schemas");
const names = (await readdir(schemaDir)).filter((f) => f.endsWith(".schema.json")).sort();

for (const file of names) {
  const schema = JSON.parse(await readFile(join(schemaDir, file), "utf8"));
  const ts = await compile(schema, basename(file, ".schema.json"), {
    bannerComment: "/* Generated by `npm run gen:types` from schemas/. Do not edit. */",
    additionalProperties: false,
    style: { singleQuote: false },
  });
  const out = join(root, `${basename(file, ".schema.json")}.ts`);
  await writeFile(out, ts, "utf8");
  console.log(`wrote ${out}`);
}
